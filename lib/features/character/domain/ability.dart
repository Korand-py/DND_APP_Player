/// Шесть характеристик SRD 5.1.
///
/// Порядок объявления — это порядок в UI, в БД и в расчётах. Менять его нельзя:
/// на нём держатся индексы и снапшоты.
enum Ability {
  strength('Сила', 'СИЛ'),
  dexterity('Ловкость', 'ЛОВ'),
  constitution('Телосложение', 'ТЕЛ'),
  intelligence('Интеллект', 'ИНТ'),
  wisdom('Мудрость', 'МУД'),
  charisma('Харизма', 'ХАР');

  const Ability(this.label, this.shortLabel);

  /// Полное название для карточек и спасбросков.
  final String label;

  /// Три буквы для плотных сеток, где полное название не влезает.
  final String shortLabel;
}
